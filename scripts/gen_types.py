"""T8.2: generate app/src/types.ts from the Pydantic models in fieldwitness.schemas.

Pydantic JSON Schema (validation mode) -> TypeScript. No extra dependency.
Fields whose default is null become optional (packs omit null interval bounds).
Usage: uv run python scripts/gen_types.py [--check]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from pydantic import BaseModel

from fieldwitness import schemas

OUT = Path(__file__).resolve().parents[1] / "app" / "src" / "types.ts"
ALIASES = {  # enum values -> exported alias name (kept for the app code)
    ("O", "D", "E", "A"): "Tag",
    ("A", "B", "C", "D"): "Grade",
    ("heat", "frost", "water_stress", "extreme_rain_bare"): "Hazard",
    ("erosion_exposure", "water_stress_share", "frost_share"): "FieldColourMetric",
    ("fieldwitness", "B0", "B1", "B2", "B3"): "HindcastMethod",
}
USED: dict[str, tuple] = {}


def lit(v: object) -> str:
    return json.dumps(v)


def ts(node: dict) -> str:
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "const" in node:
        return lit(node["const"])
    if "enum" in node:
        key = tuple(node["enum"])
        if key in ALIASES:
            USED[ALIASES[key]] = key
            return ALIASES[key]
        return " | ".join(lit(v) for v in node["enum"])
    if "anyOf" in node:
        return " | ".join(dict.fromkeys(ts(n) for n in node["anyOf"]))
    t = node.get("type")
    if t in ("number", "integer"):
        return "number"
    if t == "string":
        return "string"  # incl. date / date-time (ISO strings in JSON)
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(ts(n) for n in node["prefixItems"]) + "]"
        return (
            f"({ts(node['items'])})[]"
            if "anyOf" in node.get("items", {})
            else f"{ts(node.get('items', {}))}[]"
        )
    if t == "object":
        ap = node.get("additionalProperties")
        if isinstance(ap, dict):
            return f"Record<string, {ts(ap)}>"
        return "Record<string, unknown>"
    raise ValueError(f"unsupported schema node: {node}")


def iface(name: str, d: dict) -> str:
    req = set(d.get("required", []))
    lines = [f"export interface {name} {{"]
    for k, v in d.get("properties", {}).items():
        doc = v.get("description")
        if doc:
            lines.append(f"  /** {doc} */")
        # Optional only when the default is null (packs omit null bounds).
        optional = k not in req and v.get("default") is None
        lines.append(f"  {k}{'?' if optional else ''}: {ts(v)};")
    lines.append("}")
    return "\n".join(lines)


def main() -> int:
    models = [
        m
        for m in vars(schemas).values()
        if isinstance(m, type)
        and issubclass(m, BaseModel)
        and m is not BaseModel
        and m.__module__ == schemas.__name__
    ]
    defs: dict[str, dict] = {}
    for m in models:
        sch = m.model_json_schema(ref_template="#/$defs/{model}")
        defs.update(sch.pop("$defs", {}))
        defs[m.__name__] = sch
    body = [iface(n, defs[n]) for n in sorted(defs) if defs[n].get("type") == "object"]
    # Python-side name `Field` is the PLAN §3 model; keep it as `Field` in TS.
    USED.update({name: key for key, name in ALIASES.items()})
    alias_lines = [
        f"export type {n} = {' | '.join(lit(v) for v in key)};" for n, key in sorted(USED.items())
    ]
    text = (
        "// GENERATED by scripts/gen_types.py from fieldwitness.schemas (T8.2). Do not edit.\n"
        "// Optional (?) = field defaults to null in the Pydantic model.\n\n"
        + "\n".join(alias_lines)
        + "\n\n"
        + "\n\n".join(body)
        + "\n"
    )
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("types.ts up to date" if ok else "types.ts is STALE: run scripts/gen_types.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(defs)} models)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
